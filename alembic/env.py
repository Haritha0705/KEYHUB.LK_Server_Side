config = context.config

# Prefer DATABASE_URL from the environment (e.g. inside Docker); otherwise
# fall back to the sqlalchemy.url defined in alembic.ini for local runs.
# Migrations run over the async (asyncpg) driver to match the application.
_db_url = os.environ.get("DATABASE_URL") or config.get_main_option("sqlalchemy.url")
if _db_url:
    config.set_main_option("sqlalchemy.url", _as_async_url(_db_url))

